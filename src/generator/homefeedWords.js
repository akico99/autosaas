const ALL_TITLE_WORDS = [...HOMEFEED_WORDS, ...REVIEW_WORDS];

/**
 * 제목에 홈판 후킹 단어(자극어 or 리뷰·정보 후킹어)가 실제로 포함됐는지 검사한다.
 * 생성 결과 검증(하드 규칙 강제)에 사용.
 * @param {string} title
 * @returns {{ ok: boolean, matched: string[] }}
 */
function checkHomefeedWords(title) {
  const text = title || '';
  const matched = ALL_TITLE_WORDS.filter((w) => text.includes(w));
  return { ok: matched.length >= 1, matched };
}

