const TONES_WITH_NOTE = ['1인칭 경험담체', '내돈내산 후기체', '1인칭 팬 시점체'];

function familyOf(key) { return FAMILY_BY_KEY[key] || 'C'; }

// 평탄화한 전체 주제 목록. (각 주제에 family 태그 부착)
const SEARCH_TOPICS = SEARCH_TOPIC_GROUPS.flatMap((g) =>
  g.topics.map((t) => ({ ...t, group: g.group, family: FAMILY_BY_KEY[t.key] || 'C' })),
);

// 검색용 본문 최소 글자수(기본). 대본15: AI 브리핑이 본문 2,000바이트↑ 문서 우대 →
// 검색글은 충분히 길고 정보 밀도 높게. (한글 UTF-8 3바이트 기준 여유 있게 1,500자 목표)
const SEARCH_MIN_LENGTH = 1800;

function getSearchTopic(key) {
  const t = SEARCH_TOPICS.find((x) => x.key === key);
  if (!t) {
    throw new Error(
      `알 수 없는 검색 주제: "${key}". 사용 가능: ${SEARCH_TOPICS.map((x) => x.key).join(', ')}`,
    );
  }
  return t;
}

module.exports = {
  SEARCH_TOPIC_GROUPS,
  SEARCH_TOPICS,
  SEARCH_MIN_LENGTH,
  getSearchTopic,
  FAMILY_BY_KEY,
  SEARCH_FAMILIES,
  TONES_WITH_NOTE,
  familyOf,
};
