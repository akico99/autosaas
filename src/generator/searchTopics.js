  // B 전문가형 (신뢰·근거, 어려운 용어는 쉽게)
  health: 'B', business: 'B', society: 'B', it: 'B', education: 'B', language: 'B', car: 'B',
  // C 경험담 (직접 해본 후기)
  restaurant: 'C', domestictravel: 'C', worldtravel: 'C', parenting: 'C', cooking: 'C', art: 'C', photo: 'C', gardening: 'C', hobby: 'C', interior: 'C', pet: 'C', game: 'C', daily: 'C',
