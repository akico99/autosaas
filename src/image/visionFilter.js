const MEDIA = { jpg: 'image/jpeg', jpeg: 'image/jpeg', png: 'image/png', webp: 'image/webp', gif: 'image/gif' };
function mediaType(p) {
  const ext = (p.split('.').pop() || '').toLowerCase();
  return MEDIA[ext] || 'image/jpeg';
}

// ★비전에 보낼 이미지 인코딩 — 긴변을 50%로 줄이되 최소 1000px(그보다 작은 원본은 그대로, 절대 확대 안 함) + JPEG 재인코딩 → 토큰 절약.
//   과거 "리사이즈가 일부 포맷을 깨 전부 버림" 사고 방지 = ①못 읽으면 원본 ②리사이즈 결과가 깨지면(아주 작은 출력) 원본 ③비Electron/예외도 원본.
//   nativeImage(Electron 메인프로세스, 워터마크 크롭에도 쓰는 것)로 처리.
const VISION_MIN_PX = 1000;
const VISION_SCALE = 0.5;
function readImageForVision(path) {
  let raw;
  try { raw = fs.readFileSync(path); } catch (e) { return null; }
  const orig = { data: raw.toString('base64'), media: mediaType(path) };
  try {
    const { nativeImage } = require('electron');
    let img = nativeImage.createFromBuffer(raw);
    if (!img || img.isEmpty()) return orig; // 못 읽으면 원본(사고 방지)
    const sz = img.getSize();
    const L = Math.max(sz.width, sz.height);
    let target = Math.max(VISION_MIN_PX, Math.round(L * VISION_SCALE));
    if (target > L) target = L;
    if (target >= L) return orig; // 원본이 이미 작음(1000 이하 등) → 그대로(토큰 동일).
    const scale = target / L;
    img = img.resize({ width: Math.round(sz.width * scale), height: Math.round(sz.height * scale), quality: 'good' });
    const jpeg = img.toJPEG(82); // 안전한 JPEG로 재인코딩(webp/png 깨짐 원천 차단)
    if (jpeg && jpeg.length > 800) return { data: jpeg.toString('base64'), media: 'image/jpeg' };
    return orig; // 리사이즈 결과가 깨졌으면 원본(전부 버림 방지)
  } catch (e) { return orig; } // 비Electron·예외 = 원본 그대로
}

